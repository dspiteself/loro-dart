// Writes THIRD_PARTY_NOTICES.md: the licenses of the Rust crates compiled
// into the native library (prebuilt for the web in lib/src/web/, built by the
// build hook elsewhere) and of the Emscripten runtime linked into the web
// module. Run from the package root after changing Rust dependencies:
//
//   dart run tool/generate_notices.dart
import 'dart:convert';
import 'dart:io';

const _out = 'THIRD_PARTY_NOTICES.md';

final _licenseFile = RegExp(
  r'^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE|COPYRIGHT)',
  caseSensitive: false,
);

void main() {
  final result = Process.runSync('cargo', [
    'metadata',
    '--format-version',
    '1',
    '--manifest-path',
    'native/Cargo.toml',
  ]);
  if (result.exitCode != 0) {
    stderr.writeln(result.stderr);
    exit(1);
  }
  final meta = jsonDecode(result.stdout as String) as Map<String, dynamic>;
  final packages = {
    for (final p in (meta['packages'] as List).cast<Map<String, dynamic>>())
      p['id'] as String: p,
  };
  final nodes = {
    for (final n
        in ((meta['resolve'] as Map)['nodes'] as List)
            .cast<Map<String, dynamic>>())
      n['id'] as String: n,
  };
  final root = (meta['resolve'] as Map)['root'] as String;

  // Normal (non-dev, non-build) dependencies reachable from the root, on any
  // target platform. Proc-macro crates run at compile time only and are not
  // part of the binary, so neither they nor their dependencies are listed.
  bool isProcMacro(String id) => (packages[id]!['targets'] as List)
      .cast<Map>()
      .any((t) => (t['kind'] as List).contains('proc-macro'));
  final reachable = <String>{};
  final stack = [root];
  while (stack.isNotEmpty) {
    final id = stack.removeLast();
    if (isProcMacro(id) || !reachable.add(id)) continue;
    for (final dep in (nodes[id]!['deps'] as List).cast<Map>()) {
      final kinds = (dep['dep_kinds'] as List).cast<Map>();
      if (kinds.any((k) => k['kind'] == null)) stack.add(dep['pkg'] as String);
    }
  }
  reachable.remove(root);

  final crates = reachable.map((id) => packages[id]!).toList()
    ..sort((a, b) => (a['name'] as String).compareTo(b['name'] as String));

  // License text -> crates using it, so identical texts appear once.
  final texts = <String, List<String>>{};
  final rows = <String>[];
  for (final c in crates) {
    final name = '${c['name']} ${c['version']}';
    final dir = File(c['manifest_path'] as String).parent;
    final files =
        dir
            .listSync()
            .whereType<File>()
            .where((f) => _licenseFile.hasMatch(f.uri.pathSegments.last))
            .toList()
          ..sort((a, b) => a.path.compareTo(b.path));
    for (final f in files) {
      final text = f.readAsStringSync().replaceAll('\r\n', '\n').trim();
      if (text.isEmpty) continue;
      (texts[text] ??= []).add(name);
    }
    final repo = c['repository'] as String? ?? '';
    final license = c['license'] as String? ?? 'see repository';
    final note = files.isEmpty ? ' (no license file in the crate)' : '';
    rows.add('| $name | $license$note | $repo |');
  }

  final b = StringBuffer()
    ..writeln('# Third-party notices')
    ..writeln()
    ..writeln(
      'loro_crdt compiles the Rust crates below into its native library: '
      'prebuilt for the web in `lib/src/web/`, and built by the package\'s '
      'build hook on other platforms. Source code for every crate is '
      'available from [crates.io](https://crates.io) and the linked '
      'repositories.',
    )
    ..writeln()
    ..writeln(
      'Generated by `tool/generate_notices.dart` from `native/Cargo.lock`.',
    )
    ..writeln()
    ..writeln('| Crate | License | Repository |')
    ..writeln('| --- | --- | --- |');
  rows.forEach(b.writeln);
  b
    ..writeln()
    ..writeln('## Emscripten runtime (web build only)')
    ..writeln()
    ..writeln(
      'The web module links the Emscripten runtime and its system libraries '
      '(musl libc, libc++, libc++abi, compiler-rt, dlmalloc). Their licenses '
      'are in the [Emscripten repository]'
      '(https://github.com/emscripten-core/emscripten/tree/main/system/lib); '
      'Emscripten\'s own license follows.',
    )
    ..writeln();
  final emsdk =
      Platform.environment['EMSDK'] ?? '${Platform.environment['HOME']}/emsdk';
  final emLicense = File('$emsdk/upstream/emscripten/LICENSE');
  if (emLicense.existsSync()) {
    b
      ..writeln('```')
      ..writeln(emLicense.readAsStringSync().trim())
      ..writeln('```');
  } else {
    b.writeln(
      'See https://github.com/emscripten-core/emscripten/blob/main/LICENSE.',
    );
  }
  b
    ..writeln()
    ..writeln('## License texts')
    ..writeln();
  for (final MapEntry(key: text, value: users) in texts.entries) {
    b
      ..writeln('### ${users.join(', ')}')
      ..writeln()
      ..writeln('```')
      ..writeln(text.replaceAll('```', "'''"))
      ..writeln('```')
      ..writeln();
  }
  File(_out).writeAsStringSync(b.toString());
  stdout.writeln(
    'wrote $_out: ${crates.length} crates, ${texts.length} license texts',
  );
}
